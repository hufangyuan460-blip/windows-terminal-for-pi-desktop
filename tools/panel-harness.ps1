# Builds a browser harness for the terminal panel: the *real* renderer
# (renderer/index.html + renderer/app.js + renderer/vendor) plus a stub
# `window.pluginBridge`, so the panel's rendering layer can be checked without
# loading the plugin into PI-Desktop.
#
# Why this exists: the panel is a view inside the host, so its DOM cannot be
# reached from the Node test suite, and the host's browser panel is often
# zero-sized (no layout viewport), which makes plain measurements meaningless.
# Every generated page therefore also reports its own layout numbers, and
# `index-widths.html` embeds the `ok` page in 280/320/400/600 px frames and
# collects those reports over postMessage — that is how the narrow-panel
# criteria in docs/TEST-REPORT.md are checked.
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File tools/panel-harness.ps1
# then open these pages with PI-Desktop's browser view (or any browser):
#
#   index-ok.html      shells available -> one tab, an xterm canvas, no errors
#   index-empty.html   no shells        -> "no supported shell" + what discovery
#                                         returned + the helper path
#   index-fail.html    state rejects    -> "cannot read the terminal state" plus
#                                         an error bar with a Retry button
#   index-slow.html    snapshot at 3 s  -> "reading the shell list…" first, then
#                                         the terminal appears once it arrives
#   index-widths.html  the `ok` page in 280/320/400/600 px frames, reporting
#                      overflow, control-bar geometry and popover clamping
#
# Every page writes a JSON report into <title> and #probe 1.5 s after load,
# including `errors` (window.onerror / unhandled rejections), `Terminal`
# (typeof window.Terminal), `xtermRendered`, the layout numbers and the result
# of opening the `…` menu.

param(
  [string]$Out = (Join-Path $env:TEMP 'pi-terminal-panel-harness')
)

$ErrorActionPreference = 'Stop'

$pluginRoot = Split-Path -Parent $PSScriptRoot
$renderer = Join-Path $pluginRoot 'renderer'
if (-not (Test-Path (Join-Path $renderer 'app.js'))) {
  throw "renderer not found under $renderer"
}

if (Test-Path $Out) { Remove-Item $Out -Recurse -Force }
New-Item -ItemType Directory -Path $Out | Out-Null
Copy-Item (Join-Path $renderer '*') $Out -Recurse -Force

$stub = @'
// Stub host bridge for the terminal panel harness (generated by tools/panel-harness.ps1).
(function () {
  const mode = window.__CASE__ || 'ok';

  // Anything the page throws ends up in the report instead of only in devtools.
  window.__ERRORS__ = [];
  window.addEventListener('error', (event) => {
    window.__ERRORS__.push(String((event && event.message) || (event && event.error) || event));
  });
  window.addEventListener('unhandledrejection', (event) => {
    window.__ERRORS__.push('unhandled rejection: ' + String((event && event.reason && event.reason.message) || (event && event.reason)));
  });

  const helperPath = 'C:\\path\\to\\pi-conpty-helper.exe';
  const projectCwd = 'C:\\project';

  const catalogOk = {
    defaultShellId: 'windows-powershell',
    helperAvailable: true,
    helperPath,
    shells: [
      { id: 'windows-powershell', label: 'Windows PowerShell 5.1', available: true, path: 'C:\\Windows\\System32\\WindowsPowerShell\\v1.0\\powershell.exe', detail: '', dialect: 'powershell' },
      { id: 'cmd', label: 'Command Prompt (cmd)', available: true, path: 'C:\\Windows\\System32\\cmd.exe', detail: '', dialect: 'cmd' },
    ],
  };

  const catalogEmpty = { defaultShellId: null, helperAvailable: true, helperPath, shells: [] };

  function makeTab(id, title) {
    return {
      id,
      title,
      shellId: 'windows-powershell',
      shellLabel: title,
      shellPath: 'C:\\Windows\\System32\\WindowsPowerShell\\v1.0\\powershell.exe',
      cwd: projectCwd,
      cwdNote: null,
      cols: 80,
      rows: 24,
      status: 'running',
      exitCode: null,
      error: null,
      pid: 4321,
      active: true,
      bytes: 0,
      dropped: 0,
    };
  }

  let nextTab = 0;
  const tabs = [];

  function snapshotFor(list) {
    return {
      tabs: list,
      shells: mode === 'empty' ? catalogEmpty : catalogOk,
      limits: { maxTabs: 8, scrollbackKiB: 256 },
      cwd: projectCwd,
      cwdNote: null,
      transport: null,
      notices: [],
    };
  }

  const emptySnapshot = snapshotFor([]);

  window.pluginBridge = {
    invoke(channel, payload) {
      if (channel === 'state') {
        if (mode === 'fail') return Promise.reject(new Error('stub: state channel failed'));
        if (mode === 'slow') {
          return new Promise((resolve) => setTimeout(() => resolve(snapshotFor(tabs.slice())), 3000));
        }
        return Promise.resolve(snapshotFor(tabs.slice()));
      }
      if (channel === 'app.getAppearance') return Promise.resolve({ base: 'dark', locale: 'zh-CN' });
      if (channel === 'read') return Promise.resolve({ ok: true, tabs: {} });
      if (channel === 'create') {
        nextTab += 1;
        const requested = payload && typeof payload.shellId === 'string' && payload.shellId ? payload.shellId : 'windows-powershell';
        const label = requested === 'cmd' ? 'Command Prompt (cmd)' : 'Windows PowerShell 5.1';
        const tab = makeTab('t' + nextTab, label);
        tab.shellId = requested;
        tabs.push(tab);
        return Promise.resolve({ ok: true, tab, state: snapshotFor(tabs.slice()) });
      }
      if (channel === 'close') {
        const id = payload && payload.tabId;
        const at = tabs.findIndex((tab) => tab.id === id);
        if (at >= 0) tabs.splice(at, 1);
        return Promise.resolve({ ok: true, tab: null, state: snapshotFor(tabs.slice()) });
      }
      return Promise.resolve({ ok: true });
    },
    on() {
      return () => {};
    },
    getDroppedFilePath() {
      return null;
    },
  };

  function rectOf(selector) {
    const el = typeof selector === 'string' ? document.querySelector(selector) : selector;
    if (!el) return null;
    const rect = el.getBoundingClientRect();
    return { x: Math.round(rect.x), y: Math.round(rect.y), w: Math.round(rect.width), h: Math.round(rect.height) };
  }

  const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

  /** The session button must truncate a long name instead of pushing the icons out. */
  function longNameCheck() {
    const name = document.getElementById('session-name');
    const more = document.getElementById('more');
    const bar = document.querySelector('.bar');
    if (!name || !more || !bar) return { ellipsised: null, buttonsUsable: null };
    const previous = name.textContent;
    name.textContent = 'Windows PowerShell 5.1 ' + 'x'.repeat(60);
    const ellipsised = name.scrollWidth > name.clientWidth + 1;
    const rect = more.getBoundingClientRect();
    const barRect = bar.getBoundingClientRect();
    const usable = rect.width > 0 && rect.right <= window.innerWidth + 0.5 && Math.round(barRect.height) <= 44;
    name.textContent = previous;
    return { ellipsised, buttonsUsable: usable };
  }

  /** Several terminals, the session popover, switching, and focus going back. */
  async function driveMultiTab() {
    const result = {};
    document.getElementById('new').click();
    await sleep(150);
    document.getElementById('new').click();
    await sleep(150);
    document.getElementById('session').click();
    await sleep(100);
    const rows = [...document.querySelectorAll('#pop-sessions .item')];
    result.tabs = rows.length;
    result.labels = rows.map((row) => row.querySelector('.grow').textContent);
    result.checked = rows.filter((row) => row.getAttribute('aria-checked') === 'true').length;
    if (rows.length > 1) rows[rows.length - 1].click();
    await sleep(150);
    try {
      window.focus();
    } catch {
      // A frame that refuses focus still reports hasFocus: false below.
    }
    await sleep(60);
    const active = document.querySelector('.term-host[data-active="true"]');
    result.frameHasFocus = document.hasFocus();
    result.activeElementTag = document.activeElement ? document.activeElement.tagName : null;
    result.switchedFocusInTerminal = active ? active.contains(document.activeElement) : false;
    result.hosts = document.querySelectorAll('.term-host').length;
    result.popoverClosed = document.getElementById('pop-sessions').hidden;
    result.errors = window.__ERRORS__.slice();
    return result;
  }
  function collect() {
    const doc = document.documentElement;
    const buttons = ['new', 'new-shell', 'more'].map((id) => ({ id, ...rectOf('#' + id) }));
    const name = document.getElementById('session-name');
    const longName = longNameCheck();
    const report = {
      case: mode,
      width: window.innerWidth,
      height: window.innerHeight,
      Terminal: typeof window.Terminal,
      FitAddon: typeof window.FitAddon,
      pickerOptions: [...document.querySelectorAll('#pop-shells .item .grow')].map((node) => node.textContent),
      hint: document.getElementById('empty-hint') ? document.getElementById('empty-hint').textContent : '(no #empty-hint)',
      emptyVisible: document.getElementById('empty') ? !document.getElementById('empty').hidden : null,
      sessionName: name ? name.textContent : null,
      sessionNameEllipsised: name ? name.scrollWidth > name.clientWidth + 1 : null,
      bar: rectOf('.bar'),
      buttons,
      buttonsUsable: buttons.every((button) => button.w > 0 && button.h > 0 && button.x >= 0 && button.x + button.w <= window.innerWidth + 0.5),
      overflowX: doc.scrollWidth - doc.clientWidth,
      tabStrip: document.querySelectorAll('#tabs .tab').length,
      statusBars: document.querySelectorAll('.status').length,
      tabButtons: document.querySelectorAll('#pop-sessions .item').length,
      termHosts: document.querySelectorAll('.term-host').length,
      xtermRendered: document.querySelectorAll('.xterm').length,
      bannerHidden: document.getElementById('banner') ? document.getElementById('banner').hidden : null,
      bannerText: document.getElementById('banner') && !document.getElementById('banner').hidden
        ? document.getElementById('banner').innerText.replace(/\s+/g, ' ').trim()
        : null,
      errors: window.__ERRORS__,
      popover: window.__POPOVER__ || null,
      multi: window.__MULTI__ || null,
      longName: longName,
    };
    return report;
  }

  function publish() {
    const report = collect();
    document.title = JSON.stringify(report);
    let probe = document.getElementById('probe');
    if (!probe) {
      probe = document.createElement('pre');
      probe.id = 'probe';
      document.body.appendChild(probe);
    }
    probe.textContent = JSON.stringify(report, null, 2);
    try {
      if (window.parent && window.parent !== window) {
        window.parent.postMessage({ kind: 'pi-panel-harness', report }, '*');
      }
    } catch (error) {
      // Frames are optional; the probe above is always available.
    }
  }

  /** Open `…` and report where the popover landed, then close it again. */
  function measurePopover() {
    const more = document.getElementById('pop-more');
    const button = document.getElementById('more');
    if (!more || !button || button.disabled) return null;
    button.click();
    const rect = rectOf(more);
    const result = {
      open: !more.hidden,
      rect,
      inside: rect.x >= 0 && rect.y >= 0 && rect.x + rect.w <= window.innerWidth + 0.5 && rect.y + rect.h <= window.innerHeight + 0.5,
      items: [...more.querySelectorAll('.item')].map((item) => item.textContent.trim()),
      firstFocused: document.activeElement === more.querySelector('.item'),
    };
    document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
    result.closedByEscape = more.hidden;
    result.focusRestored = document.activeElement === button;
    return result;
  }

  window.setTimeout(async () => {
    publish();
    const popover = measurePopover();
    if (popover) {
      window.__POPOVER__ = popover;
      publish();
    }
    if (mode === 'ok') {
      window.__MULTI__ = await driveMultiTab();
      publish();
    }
  }, 1500);
})();
'@

$stubPath = Join-Path $Out 'stub.js'
[IO.File]::WriteAllText($stubPath, $stub, (New-Object Text.UTF8Encoding($false)))

$template = Get-Content (Join-Path $Out 'index.html') -Raw -Encoding UTF8
$anchor = '<script src="app.js"></script>'
if ($template.IndexOf($anchor) -lt 0) {
  throw "renderer/index.html no longer has $anchor; update this script"
}

foreach ($case in 'ok', 'empty', 'fail', 'slow') {
  $injected = "<script>window.__CASE__='$case';</script>`r`n    <script src=`"stub.js`"></script>`r`n    $anchor"
  $html = $template.Replace($anchor, $injected)
  $target = Join-Path $Out "index-$case.html"
  [IO.File]::WriteAllText($target, $html, (New-Object Text.UTF8Encoding($false)))
}

# The width page: the `ok` page in fixed-width frames, reporting their numbers.
$widths = @'
<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <title>panel widths</title>
    <style>
      body { margin: 0; font: 12px/1.5 Consolas, monospace; background: #111; color: #eee; }
      iframe { border: 0; vertical-align: top; background: #000; }
    </style>
  </head>
  <body>
    <pre id="out"></pre>
    <script>
      const WIDTHS = [280, 320, 400, 600];
      const reports = {};
      const popovers = {};
      window.__WIDTHS__ = reports;
      window.__POPOVERS__ = popovers;
      const out = document.getElementById('out');
      function render() {
        out.textContent = JSON.stringify({ reports, popovers }, null, 1);
      }
      window.addEventListener('message', (event) => {
        const payload = event.data;
        if (!payload || payload.kind !== 'pi-panel-harness') return;
        const report = payload.report;
        reports[report.width] = report;
        render();
      });
      render();
      for (const width of WIDTHS) {
        const frame = document.createElement('iframe');
        frame.width = width;
        frame.height = 620;
        frame.dataset.width = String(width);
        frame.src = 'index-ok.html';
        document.body.appendChild(frame);
      }
    </script>
  </body>
</html>
'@

